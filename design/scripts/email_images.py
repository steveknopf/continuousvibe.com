"""Builds src/lib/email-images.ts: the logo and signature used in the site's emails, as base64 PNGs.

They're attached to each email as inline images, so they show without the site being online.
Needs Pillow:  python3 design/scripts/email_images.py
"""

import base64
import io
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "public/assets"
OUT = ROOT / "src/lib/email-images.ts"


def png(img):
    buf = io.BytesIO()
    img.save(buf, "PNG", optimize=True)
    return base64.b64encode(buf.getvalue()).decode()


# Logo: 2x the size it's shown at (60px).
logo = Image.open(ASSETS / "cv-logo-trimmed.png").convert("RGBA").resize((120, 120), Image.LANCZOS)

# Sign-off: the white signature and the logo side by side on transparent, as one image for the black
# footer. 2x the size it's shown at.
H, PAD, GAP, LOGO = 104, 24, 36, 120
sig = Image.open(ASSETS / "signiture white.png").convert("RGBA")
sig = sig.crop(sig.getbbox())
sig = sig.resize((round(sig.width * H / sig.height), H), Image.LANCZOS)
panel_h = LOGO + 2 * PAD
sign_off = Image.new("RGBA", (PAD + sig.width + GAP + LOGO + PAD, panel_h), (0, 0, 0, 0))
sign_off.alpha_composite(sig, (PAD, (panel_h - H) // 2))
sign_off.alpha_composite(logo, (PAD + sig.width + GAP, PAD))

# Header wordmark: "CONTINUOUS" white and "VIBE" red, on transparent. An image because Gmail's dark mode
# recolours text on the header (red came out blue). 2x its shown size (20px bold, 2px letter spacing).
font = ImageFont.truetype("/System/Library/Fonts/Helvetica.ttc", 40, index=1)
parts = [("CONTINUOUS ", (255, 255, 255)), ("VIBE", (230, 18, 18))]
SPACING = 4
glyphs = [(ch, colour) for text, colour in parts for ch in text]
width = sum(font.getlength(ch) + SPACING for ch, _ in glyphs)
ascent, descent = font.getmetrics()
wordmark = Image.new("RGBA", (round(width), ascent + descent), (0, 0, 0, 0))
draw, x = ImageDraw.Draw(wordmark), 0.0
for ch, colour in glyphs:
    draw.text((x, 0), ch, font=font, fill=(*colour, 255))
    x += font.getlength(ch) + SPACING
wordmark = wordmark.crop(wordmark.getbbox())

OUT.write_text(
    "// Generated by design/scripts/email_images.py. Don't edit by hand.\n\n"
    f"export const LOGO_PNG = \"{png(logo)}\";\n"
    f"export const SIGN_OFF_PNG = \"{png(sign_off)}\";\n"
    f"export const WORDMARK_PNG = \"{png(wordmark)}\";\n"
    f"export const WORDMARK_SIZE = {{ width: {wordmark.width // 2}, height: {wordmark.height // 2} }};\n"
    f"export const SIGN_OFF_SIZE = {{ width: {sign_off.width // 2}, height: {sign_off.height // 2} }};\n"
)
print(f"wrote {OUT.relative_to(ROOT)}: logo 120x120, sign-off {sign_off.size}, {OUT.stat().st_size // 1024} KB")
